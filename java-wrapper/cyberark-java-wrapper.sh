#!/bin/ksh
#-----------------------------------------------------------------------------
# Application startup wrapper with CyberArk Credential Provider (CP) integration
# Platform: IBM AIX (ksh88 compatible) - native AIX commands only, no GNU tools
#
# Purpose:
#   The application reads its database password from a properties file and
#   cannot be modified to call CyberArk directly. This wrapper retrieves the
#   password from the CyberArk Vault via the CP command-line SDK at startup,
#   generates the properties file on the fly, launches the application,
#   verifies it is running, and then removes the clear-text password from disk.
#
# Result:
#   - No static password is stored on disk.
#   - The password is managed and rotated centrally in the CyberArk Vault.
#   - The application itself (the JAR file) remains unchanged.
#
# Prerequisites:
#   - CyberArk CP (AIM) is installed on this server and the CP service
#     (aimprv) is running. Check with:  ps -ef | grep '[a]imprv'
#   - An Application ID (AppID) is defined in the Vault for this application,
#     authenticated by OS user and script path (optionally hash).
#   - The AppID is a member of the Safe with "Retrieve accounts" permission.
#   - This script must be executed by the OS user defined in the AppID.
#   - The template file (see TEMPLATE below) exists and contains exactly one
#     line for the password key, with the placeholder __PASSWORD__ as value.
#   - The CyberArk platform policy for this account generates printable ASCII
#     passwords with no leading/trailing spaces (the wrapper enforces this).
#
# Usage:
#   The application must ALWAYS be started through this script
#   (from inittab, SRC, rc scripts, cron or manually). Starting the JAR
#   directly with "java -jar" will no longer work, because the real
#   properties file is only generated by this script.
#-----------------------------------------------------------------------------

#-----------------------------------------------------------------------------
# Configuration - adjust these values for your environment
#-----------------------------------------------------------------------------

# Base directory of the application. All other paths are relative to this.
APP_HOME=/opt/myapp

# JAR file name and any JVM options used by the current startup command.
JAR=$APP_HOME/app.jar
JAVA_OPTS=""

# The properties file the application actually reads.
# This file is (re)generated every time the application starts and must NOT
# be edited manually; any manual change will be overwritten on next start.
PROPS=$APP_HOME/conf/app.properties

# Template of the properties file. Identical to the real file, except the
# password line contains the placeholder __PASSWORD__, e.g.:
#     db.password=__PASSWORD__
# This is the only copy of the configuration that stays on disk permanently,
# and it never contains the real password. To change any other setting,
# edit this template, not the generated file.
TEMPLATE=$APP_HOME/conf/app.properties.tmpl

# Name of the property key that holds the password, exactly as written in
# the properties file (e.g. password, db.password, jdbc.password).
PASS_KEY=db.password

# Full path to the CyberArk CP command-line SDK.
# /opt/CARKaim is the default CP installation directory on AIX/Unix; adjust
# if CP was installed elsewhere. A full path is used on purpose so the script
# does not depend on the PATH variable of the calling user or scheduler.
# No environment variables are required for the SDK to work.
SDK=/opt/CARKaim/sdk/clipasswordsdk

# CyberArk Application ID and the account to retrieve (Safe and Object name
# as shown in PVWA; Folder is almost always Root).
APPID=MyApp
QUERY="Safe=AppSafe;Folder=Root;Object=db-prod-svc"

# Application log file and PID file.
LOG=$APP_HOME/log/app.out
PIDFILE=$APP_HOME/app.pid

# Seconds to wait before checking that the process is alive, and before
# masking the password in the properties file. Increase for slow startups.
START_WAIT=10
MASK_WAIT=20

#-----------------------------------------------------------------------------
# Helper: print an error message and exit without starting the application
#-----------------------------------------------------------------------------
die() {
    echo "ERROR: $1"
    exit 1
}

mkdir -p $APP_HOME/log

#-----------------------------------------------------------------------------
# 1. Refuse to start if the application is already running
#-----------------------------------------------------------------------------
# Two checks are made, because a PID file alone can be stale (left over from
# a crash or reboot):
#   a) the PID recorded in the PID file still belongs to a live process
#   b) a Java process running this JAR is visible in the process list
# Either one means an instance is already up; starting a second one would
# regenerate the properties file underneath the running application.
if [ -f "$PIDFILE" ] && ps -p $(cat "$PIDFILE") > /dev/null 2>&1; then
    die "Application already running (PID $(cat "$PIDFILE")). Stop it first."
fi
if ps -ef | grep "[j]ava.*$JAR" > /dev/null 2>&1; then
    die "A Java process running $JAR already exists. Stop it first."
fi

#-----------------------------------------------------------------------------
# 2. Validate the template
#-----------------------------------------------------------------------------
# The password key must appear exactly once in the template (allowing for
# optional spaces and either "=" or ":" as separator), and its value must be
# the __PASSWORD__ placeholder. If the template is wrong, the generated file
# would be wrong too, so the script stops here.
[ -r "$TEMPLATE" ] || die "Template not found or not readable: $TEMPLATE"

KEY_COUNT=$(grep -c "^[[:space:]]*${PASS_KEY}[[:space:]]*[=:]" "$TEMPLATE")
[ "$KEY_COUNT" -eq 1 ] || die "Expected exactly one '$PASS_KEY' line in template, found $KEY_COUNT"

grep "^[[:space:]]*${PASS_KEY}[[:space:]]*[=:]" "$TEMPLATE" | grep "__PASSWORD__" > /dev/null \
    || die "The '$PASS_KEY' line in the template must contain the __PASSWORD__ placeholder"

#-----------------------------------------------------------------------------
# 3. Retrieve the password from the CyberArk Vault
#-----------------------------------------------------------------------------
# Parameters:
#   AppDescs.AppID = the Application ID defined in the Vault (identifies this
#                    application to CyberArk)
#   Query          = which account to retrieve: Safe name, Folder (usually
#                    Root) and the Object (account) name as shown in PVWA
#   -o Password    = output only the password value (nothing else)
#
# The SDK does not contact the Vault itself; it asks the local CP service
# (aimprv) running on this server, which holds a secure cache of the
# credentials the AppID is allowed to use.
#
# If CP cannot return the password (CP service down, AppID not authorized,
# wrong Safe/Object name, caller user/path not matching the AppID definition)
# the script exits immediately, so the application is never started with an
# empty or invalid password.
PASS=$($SDK GetPassword -p AppDescs.AppID=$APPID -p Query="$QUERY" -o Password) \
    || die "Failed to retrieve password from CyberArk CP. Application not started."
[ -n "$PASS" ] || die "CyberArk CP returned an empty password."

#-----------------------------------------------------------------------------
# 4. Validate the password against Java properties file rules
#-----------------------------------------------------------------------------
# Java's Properties.load() has two rules that cannot be fixed by escaping:
#   - leading whitespace in a value is discarded
#   - when loaded from an InputStream the file is read as ISO-8859-1, so
#     non-ASCII characters may be corrupted
# A password violating these rules would silently break the DB connection,
# so the script refuses to start instead. Configure the CyberArk platform
# policy to generate printable ASCII passwords without leading/trailing
# spaces and this check will never trigger.
case "$PASS" in
    " "*|*" ") die "Password has leading/trailing spaces; adjust the CyberArk platform policy." ;;
    *[!\ -~]*) die "Password contains non-ASCII or control characters; adjust the CyberArk platform policy." ;;
esac

#-----------------------------------------------------------------------------
# 5. Escape the password for the Java properties format
#-----------------------------------------------------------------------------
# In a properties file the backslash is an escape character, so every "\"
# in the password must be written as "\\". No other character needs
# escaping inside a value ("=" and ":" only matter in the key).
#
# The password is passed to sed through STDIN (print -r is a ksh builtin),
# never as a command-line argument, so it is not visible in "ps" output.
PASS_ESC=$(print -r -- "$PASS" | sed 's/\\/\\\\/g')

#-----------------------------------------------------------------------------
# 6. Generate the real properties file from the template
#-----------------------------------------------------------------------------
# umask 077 makes every file created from now on readable and writable only
# by its owner (600) from the instant it is created. umask does NOT change
# the permissions of an existing file, so the old properties file is removed
# first; otherwise ">" would keep its old (possibly world-readable) mode.
umask 077
rm -f "$PROPS"

# Copy every line of the template except the password line, then append the
# password line. "print -r --" is a shell builtin that writes the string
# exactly as-is (no escape interpretation, no separate process, nothing in
# the process list).
grep -v "^[[:space:]]*${PASS_KEY}[[:space:]]*[=:]" "$TEMPLATE" > "$PROPS" \
    || die "Failed to write $PROPS"
print -r -- "${PASS_KEY}=${PASS_ESC}" >> "$PROPS"

# Explicit owner-only permissions as a safety net.
chmod 600 "$PROPS"

# Drop the password from shell variables. This shortens the lifetime of the
# in-memory copies; it is not a guaranteed secure memory wipe, and the script
# process ends shortly anyway.
unset PASS PASS_ESC

#-----------------------------------------------------------------------------
# 7. Start the application
#-----------------------------------------------------------------------------
# nohup  : keep the application running even if the terminal/session closes
# > file : redirect standard output to the log file
# 2>&1   : redirect error output to the same log file
# &      : run in the background so the script can continue
#
# NOTE: If the application is managed by AIX SRC (startsrc/stopsrc), SRC
# controls the process itself; in that case remove "nohup" and "&" and let
# SRC start this script as the subsystem command.
nohup java $JAVA_OPTS -jar $JAR > $LOG 2>&1 &

# Save the process ID of the application for monitoring and shutdown scripts.
echo $! > $PIDFILE

#-----------------------------------------------------------------------------
# 8. Verify the application is running
#-----------------------------------------------------------------------------
# After a short wait, check whether the Java process is still alive. If it
# died immediately (wrong password, DB unreachable, JAR error) the problem is
# reported right away.
#
# This only proves the process is alive, not that the DB connection
# succeeded. If the application writes a recognizable "connected" message to
# its log, add a check for it here (e.g. grep on $LOG) for a stronger test.
sleep $START_WAIT
if ps -p $(cat $PIDFILE) > /dev/null 2>&1; then
    echo "Application started (PID $(cat $PIDFILE))"
else
    die "Application failed to start. Check $LOG for details."
fi

#-----------------------------------------------------------------------------
# 9. Remove the clear-text password from the properties file
#-----------------------------------------------------------------------------
# Wait for the application to finish reading the file during startup, then
# overwrite the password line with a dummy value. After this step the
# password no longer exists in the file; it lives only in the memory of the
# running application.
#
# AIX's native "sed" does not support in-place editing (-i), so the result
# is written to a temporary file (also 600 thanks to umask) and moved over
# the original.
#
# IMPORTANT: Use this step ONLY if the application reads the properties file
# once at startup. If the application re-reads the file at runtime (for
# example when reconnecting to the database), remove or comment out this
# block; the file will then keep the password during runtime but remains
# protected with 600 permissions and is regenerated on every restart.
sleep $MASK_WAIT
sed "s|^[[:space:]]*${PASS_KEY}[[:space:]]*[=:].*|${PASS_KEY}=__REMOVED__|" "$PROPS" > "$PROPS.tmp" \
    && mv "$PROPS.tmp" "$PROPS"

exit 0
